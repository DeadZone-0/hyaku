pub(super) fn raid_wings(boss: RaidBoss, phase: BossPhase, tick: u64) -> &'static [&'static str] {
    let pose = tick / 6 % 4;
    match (boss, phase, pose) {
        (RaidBoss::AshSovereign, BossPhase::Exposed, _) => &[
            "", "", "      _.", r"   .-//:", r" .'/=/_:", r"  '\\_/:", r"    '\_\",
        ],
        (RaidBoss::AshSovereign, BossPhase::Shielded, _)
        | (RaidBoss::AshSovereign, _, 1 | 3) => &[
            "", "   _..-.", r".-'/=/=\", r"'\_/_/_:", r"  '\_\_:", "    '--'", "",
        ],
        (RaidBoss::AshSovereign, _, 0) => &[
            " .-.._", r"/=/=/=\.", r"'\_\_\=:", r"   '\_\:", "     '-'", "", "",
        ],
        (RaidBoss::AshSovereign, _, _) => &[
            "", "", "     .-.", r"  .-'//=", r"./=/=/=:", r"'\\_\_/:", "  '--..'",
        ],
        (RaidBoss::LanternSaint, BossPhase::Exposed, _) => &[
            "", "", r"  .\", r" .'|", "  ''",
        ],
        (RaidBoss::LanternSaint, _, 0 | 2) => &[
            " .-.", r"/\+:", r"\_/:", " '-'", "",
        ],
        (RaidBoss::LanternSaint, _, _) => &[
            "", " _.'", r"\+/:", r"'\_:", "  ''",
        ],
        _ => &[],
    }
}

pub(super) fn mirror_wing(glyph: char) -> char {
    match glyph {
        '/' => '\\',
        '\\' => '/',
        _ => glyph,
    }
}
